#!/usr/bin/env python3
"""Turns lib/l10n/languages.json, the one list of app languages, into everything
that depends on it:

  * lib/app/localization/app_languages.g.dart        (AppLocales.all, right-to-left set)
  * lib/core/design_system/app_theme/language_fonts.g.dart (writing system and font)
  * android/app/src/main/res/xml/locales_config.xml   (Android 13+ per-app language)

    python3 tool/gen_languages.py           # after editing languages.json or translations
    python3 tool/gen_languages.py --check   # CI: fail when stale or inconsistent

A regional variant ("base": "en", "regions": ["GB", ...]) holds only the texts that
differ from its base; phones set to one of its regions get it automatically.

Each language gets the bundled font of its writing system only if that font has
every letter its texts use; otherwise the phone's own font draws it (correct
shapes for Persian, Urdu, Japanese, Thai, ... instead of a mix of fonts).
"""
import json
import subprocess
import sys
import unicodedata

from l10n_common import (PLURAL_CATS, RES, ROOT, RTL, RTL_SCRIPTS, base_code, languages,
                         load_arb, load_manifest, message_keys, support_data)

DART = ROOT / 'lib' / 'app' / 'localization' / 'app_languages.g.dart'
FONTS = ROOT / 'lib' / 'core' / 'design_system' / 'app_theme' / 'language_fonts.g.dart'
ANDROID = RES / 'xml' / 'locales_config.xml'
HEADER = '// GENERATED by tool/gen_languages.py from lib/l10n/languages.json. Do not edit.\n'

# The bundled font tried first for each writing system (assets/fonts).
SCRIPT_FONT = {'Latn': 'Manrope', 'Cyrl': 'Manrope', 'Grek': 'Manrope',
               'Arab': 'ReadexPro', 'Deva': 'NotoSansDevanagari'}
REQUIRED = ('code', 'tag', 'native', 'english', 'script', 'intl')


def covered(font, text):
    ranges = support_data()['fonts'][font]
    missing = set()
    for ch in set(text):
        if not unicodedata.category(ch)[0] in 'LM':
            continue  # punctuation, symbols and digits fall back harmlessly
        c = ord(ch)
        if not any(a <= c <= b for a, b in ranges):
            missing.add(ch)
    return missing


def font_for(lang):
    font = SCRIPT_FONT.get(lang['script'])
    if font is None:
        return None, ''
    arb = load_arb(lang['code'])
    if lang.get('base'):
        arb = {**load_arb(lang['base']), **arb}
    text = ''.join(arb[k] for k in message_keys(arb)) + lang['native']
    missing = covered(font, text)
    if missing:
        return None, f"{lang['code']}: {font} lacks {''.join(sorted(missing))[:20]}, uses the phone's font"
    return font, ''


def locale_dart(lang):
    parts = [f"languageCode: '{base_code(lang['code'])}'"]
    if lang.get('localeScript'):
        parts.append(f"scriptCode: '{lang['localeScript']}'")
    if lang.get('country'):
        parts.append(f"countryCode: '{lang['country']}'")
    return f"Locale.fromSubtags({', '.join(parts)})"


def theme_key(lang):
    s = lang.get('localeScript')
    return f"{base_code(lang['code'])}-{s}" if s else base_code(lang['code'])


def esc(s):
    return s.replace('\\', '\\\\').replace("'", "\\'")


def render_dart(manifest):
    rtl = sorted(RTL | {base_code(l['code']) for l in manifest if l['script'] in RTL_SCRIPTS})
    out = [HEADER, "part of 'app_locales.dart';\n",
           'const _rtlLanguages = {' + ', '.join(f"'{c}'" for c in rtl) + '};\n',
           '/// Display order of the language picker (most used first).',
           'const _languages = <SupportedLanguage>[']
    for l in manifest:
        out.append(f"  SupportedLanguage(tag: '{l['tag']}', locale: {locale_dart(l)}, "
                   f"nativeName: '{esc(l['native'])}', englishName: '{esc(l['english'])}', "
                   f"intlLocale: '{l['intl']}', script: '{l['script']}'"
                   + (f", regions: [{', '.join(repr(r) for r in l['regions'])}]" if l.get('regions') else '')
                   + '),')
    out.append('];')
    return '\n'.join(out) + '\n'


def render_fonts(manifest, fonts):
    out = [HEADER, "part of '../app_theme.dart';\n",
           '/// Writing system (ISO 15924) of each app language, by `languageCode[-scriptCode]`.',
           'const _languageScripts = <String, String>{']
    manifest = [l for l in manifest if not l.get('base')]  # a variant draws like its base
    out += [f"  '{theme_key(l)}': '{l['script']}'," for l in manifest]
    out += ['};\n', '/// Bundled font that has every letter of the language; absent: the phone\'s font.',
            'const _languageFonts = <String, String>{']
    out += [f"  '{theme_key(l)}': '{fonts[l['code']]}'," for l in manifest if fonts[l['code']]]
    out.append('};')
    return '\n'.join(out) + '\n'


def render_android(manifest):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- GENERATED by tool/gen_languages.py from lib/l10n/languages.json. Do not edit. -->',
           '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">']
    out += [f'    <locale android:name="{l["tag"]}" />' for l in manifest]
    out.append('</locale-config>')
    return '\n'.join(out) + '\n'


def problems(manifest):
    errs = []
    codes = [l.get('code') for l in manifest]
    data = support_data()
    for l in manifest:
        for f in REQUIRED:
            if not l.get(f):
                errs.append(f'languages.json: {l.get("code", "?")} has no "{f}"')
        if base_code(l.get('code', '')) in ('he', 'iw'):
            errs.append('Hebrew is not part of this app')
        if l.get('intl') and l['intl'] not in data['intl_dates']:
            errs.append(f"{l['code']}: intl locale {l['intl']} has no date data; use a listed one "
                        f"(tool/data/l10n_support.json intl_dates), e.g. en")
        if l.get('code') and base_code(l['code']) not in PLURAL_CATS:
            errs.append(f"{l['code']}: add its CLDR plural categories to PLURAL_CATS (tool/l10n_common.py)")
        if (l.get('script') in RTL_SCRIPTS) != (base_code(l.get('code', '')) in RTL):
            errs.append(f"{l['code']}: script {l.get('script')} and the RTL list in l10n_common.py disagree")
    for c in sorted(set(codes) - set(languages())):
        errs.append(f'languages.json lists {c} but lib/l10n/app_{c}.arb is missing')
    for c in sorted(set(languages()) - set(codes)):
        errs.append(f'app_{c}.arb exists but {c} is not in lib/l10n/languages.json')
    for l in manifest:
        if l.get('base') and l['base'] not in codes:
            errs.append(f"{l['code']}: base {l['base']} is not in languages.json")
        if l.get('base') and not l.get('regions'):
            errs.append(f"{l['code']}: a regional variant needs its \"regions\" (countries that get it)")
    if len(set(codes)) != len(codes) or len({l['tag'] for l in manifest}) != len(manifest):
        errs.append('languages.json: duplicate code or tag')
    return errs


def formatted(path, text):
    """The text as `dart format` writes it here, so formatting never makes it stale."""
    tmp = path.with_name('_format_check.g.dart')
    try:
        tmp.write_text(text, encoding='utf-8')
        subprocess.run(['dart', 'format', str(tmp)], check=True, capture_output=True, cwd=ROOT)
        return tmp.read_text(encoding='utf-8')
    finally:
        tmp.unlink(missing_ok=True)


def main():
    manifest = load_manifest()
    errs = problems(manifest)
    if errs:
        sys.exit('\n'.join(errs))
    fonts, notes = {}, []
    for l in manifest:
        fonts[l['code']], note = font_for(l)
        if note:
            notes.append(note)
    outputs = {DART: formatted(DART, render_dart(manifest)),
               FONTS: formatted(FONTS, render_fonts(manifest, fonts)),
               ANDROID: render_android(manifest)}
    if '--check' in sys.argv:
        stale = [p for p, t in outputs.items() if not p.exists() or p.read_text(encoding='utf-8') != t]
        if stale:
            sys.exit('stale: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale)
                     + '\nrun python3 tool/gen_languages.py')
        print(f'languages OK: {len(manifest)}')
        return
    for p, t in outputs.items():
        p.parent.mkdir(exist_ok=True)
        p.write_text(t, encoding='utf-8')
        print('wrote', p.relative_to(ROOT))
    for n in notes:
        print('font:', n)


if __name__ == '__main__':
    main()
