#!/usr/bin/env python3
"""Third-party license audit for Deep Focus.

    python3 tool/third_party_licenses.py           # rewrite THIRD_PARTY_LICENSES.md
    python3 tool/third_party_licenses.py --check   # exit 1 on a disallowed license
                                                   # or when the file is out of date

Reads pubspec.lock and each package's license file from the pub cache (run
`flutter pub get` first). Allowed: MIT, BSD, Apache-2.0, ISC, Zlib, CC0 /
public domain, SIL OFL. MPL-2.0 is accepted only for packages listed in
DESKTOP_ONLY (never compiled into the Android app). GPL/LGPL/AGPL fail.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'THIRD_PARTY_LICENSES.md')
PUB = os.environ.get('PUB_CACHE', os.path.expanduser('~/.pub-cache'))
ALLOWED = {'MIT', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', 'ISC', 'Zlib', 'Public domain',
           'OFL-1.1', 'BSD-3-Clause (Flutter SDK)'}
DESKTOP_ONLY = {'dbus'}  # Linux implementations of file_picker / notifications only
DEV = {'build_runner', 'drift_dev', 'flutter_test', 'flutter_lints', 'lints', 'test'}

HEAD = """# Third-party licenses

Generated by `tool/third_party_licenses.py` from `pubspec.lock` and the license file shipped
with each package; CI runs it with `--check`. Every dependency uses a permissive license that
allows commercial distribution. No GPL, LGPL or AGPL code is used.

The full license texts are shown in the app: **Settings → About → Licenses** (Flutter's
license page, which also lists the bundled fonts, registered in
`lib/app/bootstrap/font_licenses.dart`).

## Fonts and icons (bundled assets)

| Asset | License |
|---|---|
| Manrope (`assets/fonts/Manrope.ttf`) | SIL Open Font License 1.1 (`assets/fonts/OFL-Manrope.txt`) |
| Readex Pro (`assets/fonts/ReadexPro.ttf`) | SIL Open Font License 1.1 (`assets/fonts/OFL-ReadexPro.txt`) |
| Noto Sans Devanagari (`assets/fonts/NotoSansDevanagari.ttf`) | SIL Open Font License 1.1 (`assets/fonts/OFL-NotoSansDevanagari.txt`) |
| Material Icons (Flutter SDK) | Apache-2.0 |

## Android libraries (native)

| Library | License | Note |
|---|---|---|
| AndroidX, Kotlin standard library, desugar_jdk_libs | Apache-2.0 | |
| Google Play Integrity (`com.google.android.play:integrity`) | Android Software Development Kit License (proprietary, free to use) | Not open source. Added by the owner; it needs Google Play services and a network connection, and the app works fully offline without it. See docs/ADR.md (ADR-009). |
| SQLite3 Multiple Ciphers (via `sqlite3`) | MIT (SQLite itself: public domain) | |

## Dart and Flutter packages

| Package | Version | License | Use |
|---|---|---|---|
"""

NOTES = """
### Notes

- `dbus` (MPL-2.0) is only used by the Linux desktop implementations of `file_picker` and
  `flutter_local_notifications`; it is not part of the Android app. MPL-2.0 is a file-level
  license that permits commercial use.
- Packages marked "build/test only" are development tools and are not shipped in the app.
"""


def classify(t):
    t2 = t.lower()
    if 'gnu affero' in t2:
        return 'AGPL'
    if 'gnu lesser' in t2 or 'gnu library general' in t2:
        return 'LGPL'
    if 'gnu general public' in t2:
        return 'GPL'
    if 'apache license' in t2 and 'version 2.0' in t2:
        return 'Apache-2.0'
    if 'permission is hereby granted, free of charge' in t2:
        return 'MIT'
    if 'redistribution and use in source and binary forms' in t2:
        return 'BSD-3-Clause' if ('neither the name' in t2 or 'names of its' in t2) else 'BSD-2-Clause'
    if 'mozilla public license' in t2:
        return 'MPL-2.0'
    if 'isc license' in t2 or 'permission to use, copy, modify, and/or distribute' in t2:
        return 'ISC'
    if 'sil open font license' in t2:
        return 'OFL-1.1'
    if 'zlib' in t2:
        return 'Zlib'
    if 'public domain' in t2 or 'unlicense' in t2 or 'cc0' in t2:
        return 'Public domain'
    return None


def parse_lock(path):
    pkgs, cur = {}, None
    for line in open(path):
        m = re.match(r'^  ([A-Za-z0-9_]+):\s*$', line)
        if m:
            cur = pkgs.setdefault(m.group(1), {})
            continue
        m = re.match(r'^    (dependency|source|version): "?([^"\n]+)"?\s*$', line)
        if m and cur is not None:
            cur[m.group(1)] = m.group(2)
    return pkgs


def license_of(name, ver, src):
    if src == 'sdk':
        return {'BSD-3-Clause (Flutter SDK)'}
    d = os.path.join(PUB, 'hosted', 'pub.dev', f'{name}-{ver}')
    for f in ('LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'license'):
        p = os.path.join(d, f)
        if os.path.exists(p):
            text = open(p, errors='ignore').read()
            # Bundles such as sqlite3 list several licenses separated by rules.
            kinds = {k for part in re.split(r'\n-{5,}\n|\n={5,}\n', text) if (k := classify(part))}
            return kinds or {'UNKNOWN'}
    return {'NO LICENSE FILE'}


def main():
    pkgs = parse_lock(os.path.join(ROOT, 'pubspec.lock'))
    rows, bad = [], []
    for name in sorted(pkgs):
        p = pkgs[name]
        kinds = license_of(name, p.get('version', ''), p.get('source'))
        # A GPL mention inside an otherwise MPL text is the MPL's compatibility clause.
        if 'MPL-2.0' in kinds:
            kinds -= {'GPL', 'LGPL', 'AGPL'}
        dep = p.get('dependency', '')
        use = 'build/test only' if name in DEV or dep == 'direct dev' else (
            'app' if dep == 'direct main' else 'transitive')
        ok = kinds <= ALLOWED or (name in DESKTOP_ONLY and kinds <= ALLOWED | {'MPL-2.0'})
        if not ok:
            bad.append(f'{name} {p.get("version")}: {" + ".join(sorted(kinds))}')
        rows.append(f'| {name} | {p.get("version", "")} | {" + ".join(sorted(kinds))} | {use} |')
    text = HEAD + '\n'.join(rows) + '\n' + NOTES
    if bad:
        print('Disallowed or unknown licenses:\n  ' + '\n  '.join(bad))
        sys.exit(1)
    if '--check' in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ''
        if current != text:
            print('THIRD_PARTY_LICENSES.md is out of date: run python3 tool/third_party_licenses.py')
            sys.exit(1)
        print(f'licenses OK ({len(rows)} packages)')
        return
    open(OUT, 'w').write(text)
    print(f'wrote {OUT} ({len(rows)} packages)')


if __name__ == '__main__':
    main()
