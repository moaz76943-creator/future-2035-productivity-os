#!/usr/bin/env python3
"""Generates lib/l10n/custom/custom_l10n.g.dart from the generated AppLocalizations.

    flutter gen-l10n && python3 tool/gen_l10n_custom.py          # write
    python3 tool/gen_l10n_custom.py --check                       # CI: fail when stale

The file wraps AppLocalizations so the user's own wording (Settings → Language →
Rename words) replaces any plain text; texts with placeholders are passed
through unchanged. Nothing here is edited by hand, so new keys and new
languages need no extra work.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'lib' / 'l10n' / 'gen' / 'app_localizations.dart'
OUT = ROOT / 'lib' / 'l10n' / 'custom' / 'custom_l10n.g.dart'


def members():
    text = SRC.read_text(encoding='utf-8')
    body = text[text.index('abstract class AppLocalizations {'):text.index('class _AppLocalizationsDelegate')]
    getters = re.findall(r'^  String get (\w+);', body, re.M)
    methods = []
    for m in re.finditer(r'^  String (\w+)\(([^;]*?)\);', body, re.M | re.S):
        params = ' '.join(m.group(2).split()).rstrip(', ').rstrip(',')
        names = [p.split()[-1] for p in params.split(',') if p.strip()]
        methods.append((m.group(1), params, names))
    return getters, methods


def render():
    getters, methods = members()
    out = ['// GENERATED by tool/gen_l10n_custom.py from lib/l10n/gen/app_localizations.dart.',
           '// Do not edit: run `flutter gen-l10n && python3 tool/gen_l10n_custom.py`.',
           '// ignore_for_file: type=lint', '',
           "part of 'custom_words.dart';", '',
           'class _CustomL10n extends AppLocalizations {',
           '  _CustomL10n(this._b, this._o) : super(_b.localeName);',
           '  final AppLocalizations _b;',
           '  final Map<String, String> _o;', '']
    for g in getters:
        out.append(f"  @override\n  String get {g} => _o['{g}'] ?? _b.{g};")
    for name, params, names in methods:
        out.append(f"  @override\n  String {name}({params}) => _b.{name}({', '.join(names)});")
    out += ['}', '', '/// Every plain text the user can rename, in the order of the English file.',
            'const customWordKeys = <String>[']
    out += [f"  '{g}'," for g in getters]
    out += ['];', '', '/// The current app-language text of [key] (one of [customWordKeys]).',
            'String customWordBase(AppLocalizations l, String key) => switch (key) {']
    out += [f"  '{g}' => l.{g}," for g in getters]
    out += ["  _ => '',", '};', '']
    return '\n'.join(out)


def formatted(text):
    """The text as `dart format` writes it in this package, so formatting the repo never makes it stale."""
    tmp = OUT.with_name('_format_check.g.dart')
    try:
        tmp.write_text(text, encoding='utf-8')
        subprocess.run(['dart', 'format', str(tmp)], check=True, capture_output=True, cwd=ROOT)
        return tmp.read_text(encoding='utf-8')
    finally:
        tmp.unlink(missing_ok=True)


if __name__ == '__main__':
    text = formatted(render())
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit('lib/l10n/custom/custom_l10n.g.dart is stale: run python3 tool/gen_l10n_custom.py')
        print('custom wording layer OK')
    else:
        OUT.write_text(text, encoding='utf-8')
        print('wrote', OUT.relative_to(ROOT))
