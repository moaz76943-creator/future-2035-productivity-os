#!/usr/bin/env python3
"""Render build/control_inventory.json (written by
test/widget/inventory/control_inventory_test.dart) as docs/qa/CONTROL_INVENTORY.md."""
import collections, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
rows = json.loads((ROOT / 'build' / 'control_inventory.json').read_text())
by_screen = collections.OrderedDict()
for r in rows:
    by_screen.setdefault(r['screen'], []).append(r)
counts = collections.Counter(r['result'] for r in rows)
MEANING = {
    'OK': 'Tapped with a real pointer; the route, an overlay or the screen state changed.',
    'OK_ALREADY_SELECTED': 'Already the current choice (selected tab/chip/segment); re-tapping is a no-op by design.',
    'OK_VERIFIED_SEPARATELY': 'Harness limitation on that screen; behaviour verified by a dedicated test (see the test source).',
    'TEXT_INPUT': 'Text field; covered by the screen\'s own widget tests (typing, validation, saving).',
    'DISABLED': 'Disabled by design in this state (e.g. Add with empty input).',
}
out = ['# Control inventory — FUTURE 2035', '',
       'Generated by `flutter test test/widget/inventory` then `python3 tool/control_inventory_report.py`.',
       'Environment: widget tests on Flutter 3.50.0, 412x915 logical px, English, realistic seeded data',
       '(project, task with subtask, event, note, deck with 2 cards, goal, habit). Every page is walked a',
       'viewport at a time. This is not an on-device test (TalkBack, real touch, OEM behaviour are NOT covered).', '',
       f'**{len(rows)} controls on {len(by_screen)} screens.** ' + ', '.join(f'{k}: {v}' for k, v in sorted(counts.items())), '',
       'The test fails on: an exception from a tap, a control that does nothing (pointer and accessibility action),',
       'an unlabeled control, or a fully visible touch target smaller than 44x44.', '',
       '| Result | Meaning |', '|---|---|'] + [f'| {k} | {v} |' for k, v in MEANING.items()] + ['']
for screen, items in by_screen.items():
    out += [f'## `{screen}`', '', '| Control (accessibility label) | Role | Size | Result |', '|---|---|---|---|']
    for r in items:
        label = (r['label'] or '(none)').replace('|', '/')[:90]
        out.append(f"| {label} | {r['role']} | {r['size']} | {r['result']} |")
    out.append('')
dest = ROOT / 'docs' / 'qa' / 'CONTROL_INVENTORY.md'
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text('\n'.join(out))
print(f'wrote {dest.relative_to(ROOT)}: {len(rows)} controls')
