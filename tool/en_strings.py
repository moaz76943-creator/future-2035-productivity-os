import glob, os
for frag in sorted(glob.glob(os.path.join(os.path.dirname(__file__), 'strings', '*.json'))):
    for k, v in json.load(open(frag, encoding='utf-8')).items():
        if k in S:
            raise SystemExit(f'duplicate key {k} in {frag}')
        S[k] = (v['text'], v['desc'], v.get('placeholders', {}))

out = collections.OrderedDict()
out['@@locale'] = 'en'
for k,(t,d,ph) in S.items():
    out[k] = t
    meta = {'description': d}
    if ph:
        meta['placeholders'] = {n: {'type': ty} for n,ty in ph.items()}
    out['@'+k] = meta
json.dump(out, open('lib/l10n/app_en.arb','w'), ensure_ascii=False, indent=2)
